from datetime import datetime
from typing import Dict, Any, List, Optional
from pydantic import Field
from app.models.base import BaseMongoModel, PyObjectId

class ResponseOptimization(BaseMongoModel):
    """Tracks a single automated continuous optimization run for a specific tenant organization."""
    organization_id: str = Field(..., description="Organization tenant context boundary")
    status: str = Field(default="PENDING", description="PENDING, COMPLETED, FAILED")
    optimization_type: str = Field(default="CONSOLIDATED", description="POLICY_TUNING, PLAYBOOK_TUNING, DETECTION_FEEDBACK, AUTOMATION_TUNING, CONSOLIDATED")
    source_window_start: datetime = Field(..., description="Start window of the analyzed outcomes")
    source_window_end: datetime = Field(..., description="End window of the analyzed outcomes")
    metrics_snapshot: Dict[str, Any] = Field(default_factory=dict, description="Snapshot stats of MTTR/MTTC, success rate, etc.")
    recommendation_count: int = Field(default=0, description="Number of generated recommendations")
    simulation_status: str = Field(default="NOT_STARTED", description="NOT_STARTED, SIMULATING, COMPLETED, FAILED")
    approval_status: str = Field(default="PENDING", description="PENDING, PARTIALLY_APPROVED, APPROVED, REJECTED")
    audit_reference: Optional[str] = Field(None, description="GRC compliance audit or log trail code")

class ResponseTuningRecommendation(BaseMongoModel):
    """A single tuning advice generated by the analyzer, subject to simulation and governance approval."""
    organization_id: str = Field(..., description="Organization tenant context boundary")
    optimization_id: str = Field(..., description="Parent optimization run ID reference")
    recommendation_type: str = Field(..., description="POLICY_TUNING, PLAYBOOK_TUNING, DETECTION_FEEDBACK, AUTOMATION_TUNING")
    target_type: str = Field(..., description="POLICY, PLAYBOOK, DETECTION")
    target_id: str = Field(..., description="Target policy identifier, playbook ID, or detection rule key")
    current_configuration: Dict[str, Any] = Field(default_factory=dict, description="Active settings payload")
    proposed_configuration: Dict[str, Any] = Field(default_factory=dict, description="Tuned settings suggestion")
    reason: str = Field(..., description="Explainable reason text for the adjustment")
    evidence: Dict[str, Any] = Field(default_factory=dict, description="Metrics facts justifying the change")
    confidence: float = Field(default=0.0, description="Confidence score (0.0 - 100.0) based on sample sizes and consistency")
    expected_impact: Dict[str, Any] = Field(default_factory=dict, description="Predicted shifts in automation and success rates")
    risk_level: str = Field(default="LOW", description="LOW, MEDIUM, HIGH risk assessment")
    affected_actions: List[str] = Field(default_factory=list, description="Remediation actions impacted")
    affected_playbooks: List[str] = Field(default_factory=list, description="SOAR Playbooks impacted")
    affected_policies: List[str] = Field(default_factory=list, description="Policy rules impacted")
    status: str = Field(default="PROPOSED", description="PROPOSED, SIMULATING, SIMULATED, PENDING_APPROVAL, APPROVED, REJECTED, APPLIED, EXPIRED, CANCELLED")
    reviewed_at: Optional[datetime] = None
    reviewed_by: Optional[str] = None
